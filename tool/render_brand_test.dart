import 'dart:io';
import 'dart:math' as math;
import 'dart:ui' as ui;
import 'dart:ui' show Color;

import 'package:contextlens/core/theme/colors.dart';
import 'package:contextlens/core/widgets/lens_mark.dart';
import 'package:contextlens/features/splash/splash_page.dart';
import 'package:flutter_test/flutter_test.dart';

// Renders every brand asset from LensMarkPainter so they share one geometry.
// Run: flutter test tool/render_brand_test.dart
// Then: dart run flutter_launcher_icons && dart run flutter_native_splash:create

const _ring = Color(0xFF3DD6C6);
const _highlight = Color(0xFF9CF2E8);
const _background = Color(0xFF0B0F14);
const _white = Color(0xFFFFFFFF);

/// Android's adaptive icon keeps a 66 of 108 dp circle visible; the mark
/// is scaled so its farthest point (the badge edge) stays inside it.
const double _safeRadius = 0.5 * 66 / 108;
const double _foregroundScale = _safeRadius / LensGeometry.extent * 0.98;

Future<void> _png(
  String path,
  int canvas, {
  Color? background,
  double scale = 1,
  Color ring = _ring,
  Color highlight = _highlight,
  bool circleMask = false,
}) async {
  final recorder = ui.PictureRecorder();
  final c = ui.Canvas(recorder);
  final size = canvas.toDouble();
  if (circleMask) {
    c.clipPath(
      ui.Path()..addOval(ui.Rect.fromLTWH(0, 0, size, size)),
      doAntiAlias: true,
    );
  }
  if (background != null) {
    c.drawRect(
      ui.Rect.fromLTWH(0, 0, size, size),
      ui.Paint()..color = background,
    );
  }
  final side = size * scale;
  c
    ..save()
    ..translate((size - side) / 2, (size - side) / 2);
  LensMarkPainter(
    color: ring,
    highlight: highlight,
  ).paint(c, ui.Size.square(side));
  c.restore();

  final image = await recorder.endRecording().toImage(canvas, canvas);
  final bytes = await image.toByteData(format: ui.ImageByteFormat.png);
  File(path)
    ..createSync(recursive: true)
    ..writeAsBytesSync(bytes!.buffer.asUint8List());
}

String _hex(Color c) =>
    '#${(c.toARGB32() & 0xFFFFFF).toRadixString(16).padLeft(6, '0').toUpperCase()}';

String _n(double v) => (v * 1024).toStringAsFixed(2);

/// The static mark as a flat SVG on a 1024 canvas.
String _svg() {
  const c = 0.5;
  final badge = LensGeometry.badgeCenter(const ui.Offset(c, c), 1);
  const inner =
      LensGeometry.ringOuter - LensGeometry.ringStroke - LensGeometry.scanInset;
  final half = math.sqrt(
    inner * inner - LensGeometry.scanY * LensGeometry.scanY,
  );
  const a0 = LensGeometry.glintStart;
  const a1 = LensGeometry.glintStart + LensGeometry.glintSweep;
  ui.Offset onArc(double angle, double r) =>
      ui.Offset(c + r * math.cos(angle), c + r * math.sin(angle));
  final p0 = onArc(a0, LensGeometry.glintRadius);
  final p1 = onArc(a1, LensGeometry.glintRadius);
  const r = LensGeometry.badgeRadius;
  final check = [
    ui.Offset(badge.dx - r * 0.42, badge.dy + r * 0.02),
    ui.Offset(badge.dx - r * 0.12, badge.dy + r * 0.32),
    ui.Offset(badge.dx + r * 0.44, badge.dy - r * 0.28),
  ];

  return '''
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">
  <!-- Generated by tool/render_brand_test.dart from LensGeometry. -->
  <defs>
    <mask id="badge-cut">
      <rect width="1024" height="1024" fill="#FFFFFF"/>
      <circle cx="${_n(badge.dx)}" cy="${_n(badge.dy)}" r="${_n(r + LensGeometry.badgeGap)}" fill="#000000"/>
    </mask>
  </defs>
  <rect width="1024" height="1024" fill="${_hex(_background)}"/>
  <g mask="url(#badge-cut)" fill="none" stroke-linecap="round">
    <circle cx="512" cy="512" r="${_n(LensGeometry.ringRadius)}" stroke="${_hex(_ring)}" stroke-width="${_n(LensGeometry.ringStroke)}"/>
    <path d="M ${_n(p0.dx)} ${_n(p0.dy)} A ${_n(LensGeometry.glintRadius)} ${_n(LensGeometry.glintRadius)} 0 0 1 ${_n(p1.dx)} ${_n(p1.dy)}" stroke="${_hex(_highlight)}" stroke-width="${_n(LensGeometry.glintStroke)}"/>
    <line x1="${_n(c - half)}" y1="${_n(c + LensGeometry.scanY)}" x2="${_n(c + half)}" y2="${_n(c + LensGeometry.scanY)}" stroke="${_hex(_ring)}" stroke-opacity="${LensGeometry.scanOpacity}" stroke-width="${_n(LensGeometry.scanStroke)}"/>
  </g>
  <circle cx="${_n(badge.dx)}" cy="${_n(badge.dy)}" r="${_n(r)}" fill="${_hex(_ring)}"/>
  <polyline points="${check.map((p) => '${_n(p.dx)},${_n(p.dy)}').join(' ')}" fill="none" stroke="${_hex(_background)}" stroke-width="${_n(LensGeometry.checkStroke)}" stroke-linecap="round" stroke-linejoin="round"/>
</svg>
''';
}

void main() {
  test('render brand assets', () async {
    File('docs/brand/lens_mark.svg').writeAsStringSync(_svg());

    // Launcher icons (flutter_launcher_icons inputs).
    await _png('assets/icon/icon.png', 1024, background: _background);
    await _png('assets/icon/foreground.png', 1024, scale: _foregroundScale);
    await _png(
      'assets/icon/monochrome.png',
      1024,
      scale: _foregroundScale,
      ring: _white,
      highlight: _white.withValues(alpha: 0.6),
    );

    // Native splash, 4x of the 96 dp intro mark, on the splash background.
    const mark = SplashPage.markSize * 4;
    await _png(
      'assets/splash/lens_mark.png',
      mark.toInt(),
      ring: AppPalette.dark.primary,
    );
    // Android 12 shows a 768 px circle of this 1152 px image.
    await _png(
      'assets/splash/lens_mark_android12.png',
      1152,
      scale: mark / 1152,
      ring: AppPalette.dark.primary,
    );

    // Previews at launcher sizes, drawn natively at each size.
    for (final size in [48, 192]) {
      await _png(
        'docs/brand/preview_$size.png',
        size,
        background: _background,
        scale: _foregroundScale * 108 / 72,
        circleMask: true,
      );
    }
  });
}
